import { sql } from "drizzle-orm";
import { index, integer, primaryKey, sqliteTable, text } from "drizzle-orm/sqlite-core";

// ---------------------------------------------------------------------------
// better-auth core tables. Object keys must match better-auth field names.
// ---------------------------------------------------------------------------

const timestamps = {
  createdAt: integer("created_at", { mode: "timestamp_ms" })
    .notNull()
    .default(sql`(unixepoch() * 1000)`),
  updatedAt: integer("updated_at", { mode: "timestamp_ms" })
    .notNull()
    .default(sql`(unixepoch() * 1000)`),
};

export const user = sqliteTable("user", {
  id: text("id").primaryKey(),
  name: text("name").notNull(),
  email: text("email").notNull().unique(),
  emailVerified: integer("email_verified", { mode: "boolean" }).notNull().default(false),
  image: text("image"),
  ...timestamps,
});

export const session = sqliteTable(
  "session",
  {
    id: text("id").primaryKey(),
    expiresAt: integer("expires_at", { mode: "timestamp_ms" }).notNull(),
    token: text("token").notNull().unique(),
    ipAddress: text("ip_address"),
    userAgent: text("user_agent"),
    userId: text("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    ...timestamps,
  },
  (t) => [index("session_user_idx").on(t.userId)],
);

export const account = sqliteTable(
  "account",
  {
    id: text("id").primaryKey(),
    accountId: text("account_id").notNull(),
    providerId: text("provider_id").notNull(),
    userId: text("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    accessToken: text("access_token"),
    refreshToken: text("refresh_token"),
    idToken: text("id_token"),
    accessTokenExpiresAt: integer("access_token_expires_at", { mode: "timestamp_ms" }),
    refreshTokenExpiresAt: integer("refresh_token_expires_at", { mode: "timestamp_ms" }),
    scope: text("scope"),
    password: text("password"),
    ...timestamps,
  },
  (t) => [index("account_user_idx").on(t.userId)],
);

export const verification = sqliteTable(
  "verification",
  {
    id: text("id").primaryKey(),
    identifier: text("identifier").notNull(),
    value: text("value").notNull(),
    expiresAt: integer("expires_at", { mode: "timestamp_ms" }).notNull(),
    ...timestamps,
  },
  (t) => [index("verification_identifier_idx").on(t.identifier)],
);

// ---------------------------------------------------------------------------
// App tables. Times are integer epoch milliseconds so every client can use
// them without date parsing.
// ---------------------------------------------------------------------------

export const items = sqliteTable(
  "items",
  {
    id: text("id").primaryKey(), // UUIDv7, generated by the client
    userId: text("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    kind: text("kind", { enum: ["note", "link"] }).notNull(),
    text: text("text").notNull().default(""),
    url: text("url"),
    title: text("title"),
    description: text("description"),
    siteName: text("site_name"),
    faviconUrl: text("favicon_url"),
    pinned: integer("pinned", { mode: "boolean" }).notNull().default(false),
    archived: integer("archived", { mode: "boolean" }).notNull().default(false),
    tags: text("tags", { mode: "json" })
      .$type<string[]>()
      .notNull()
      .default(sql`'[]'`),
    createdAt: integer("created_at").notNull(),
    updatedAt: integer("updated_at").notNull(), // client clock, used for last-writer-wins
    deletedAt: integer("deleted_at"),
    rev: integer("rev").notNull(), // server-assigned, increases per user
  },
  (t) => [
    index("items_user_rev_idx").on(t.userId, t.rev),
    index("items_user_feed_idx").on(t.userId, t.pinned, t.createdAt),
  ],
);

export const itemTags = sqliteTable(
  "item_tags",
  {
    itemId: text("item_id")
      .notNull()
      .references(() => items.id, { onDelete: "cascade" }),
    userId: text("user_id").notNull(),
    tag: text("tag").notNull(),
  },
  (t) => [primaryKey({ columns: [t.itemId, t.tag] }), index("item_tags_user_tag_idx").on(t.userId, t.tag)],
);

/** Per-user revision counter. */
export const userSync = sqliteTable("user_sync", {
  userId: text("user_id")
    .primaryKey()
    .references(() => user.id, { onDelete: "cascade" }),
  rev: integer("rev").notNull().default(0),
});

/** Remembers pushed mutations so retries are idempotent. */
export const appliedMutations = sqliteTable(
  "applied_mutations",
  {
    mutationId: text("mutation_id").notNull(),
    userId: text("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    itemId: text("item_id").notNull(),
    status: text("status", { enum: ["applied", "stale"] }).notNull(),
    rev: integer("rev").notNull(),
    appliedAt: integer("applied_at").notNull(),
  },
  (t) => [primaryKey({ columns: [t.userId, t.mutationId] })],
);

export type ItemRow = typeof items.$inferSelect;
